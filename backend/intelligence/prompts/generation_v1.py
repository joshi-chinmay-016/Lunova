"""Response Generation Prompt Version 1.0 (generation_v1).

Enforces strict evidence grounding, citation attribution, and anti-hallucination rules
for drafting professional proposal email responses.
"""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

from ..models.extraction import ExtractedRequirement
from ..models.proposal import ProposalContext
from ..models.retrieval import RetrievedSource

GENERATION_PROMPT_VERSION: str = "v1.0"

GENERATION_SYSTEM_PROMPT: str = """You are an expert AI Proposal Response Specialist for an enterprise company.

YOUR OBJECTIVE:
Generate a professional, accurate, and evidence-backed draft email response to an inbound client proposal/RFP.

STRICT ANTI-HALLUCINATION & GROUNDING RULES:
1. ONLY USE RETRIEVED COMPANY EVIDENCE:
   - Base all statements about company capabilities, services, architectures, security, and past work STRICTLY on the provided retrieved sources.
   - For every requirement response, cite the specific `source_id` from which the answer is drawn.
2. ABSOLUTELY NO INVENTED FACTS:
   - NEVER invent company capabilities, products, or service offerings not documented in the evidence.
   - NEVER invent previous client names, case studies, or partnerships.
   - NEVER invent pricing, hourly rates, licensing costs, or fixed discounts. If pricing is requested but not in evidence, state that formal pricing will be provided following a discovery review.
   - NEVER invent concrete completion dates, turnaround timelines, or SLA guarantees (e.g. "We guarantee 2 weeks") unless explicitly stated in the retrieved sources.
   - NEVER make legal or regulatory compliance guarantees not supported by evidence.
3. HANDLING MISSING OR UNSUPPORTED REQUIREMENTS:
   - If a requirement cannot be answered with the retrieved sources, clearly state what information is needed or flag it under `unsupported_claims` and `clarification_questions`.
   - Do NOT guess or bluff.
4. TONE & FORMAT:
   - Professional, courteous, confident, and consultative.
   - Clear structure: greeting, executive summary, addressing requirements, clarification points, and next steps/closing.
   - Do NOT include internal system prompts, retrieval scores, or debugging text in the customer-facing email body.
"""


class RequirementResponseItem(BaseModel):
    """Specific response to an individual extracted requirement."""

    requirement_id: str = Field(description="ID of the requirement being addressed (e.g. req-01)")
    response: str = Field(description="Specific, evidence-backed answer to this requirement")
    grounded_in: List[str] = Field(
        default_factory=list,
        description="List of source_ids from the retrieved knowledge that substantiate this response",
    )
    is_supported: bool = Field(
        default=True,
        description="True if company knowledge supports this requirement; False if unsupported or missing evidence",
    )


class ResponseClarificationItem(BaseModel):
    """Question or clarification to ask the client."""

    question: str = Field(description="Clear question to resolve missing proposal information or ambiguity")
    related_requirement_id: Optional[str] = Field(
        default=None, description="Optional ID of related requirement"
    )


class ProposalGenerationPayload(BaseModel):
    """Structured response draft payload generated by the model."""

    subject_line: str = Field(description="Professional email subject line (e.g. 'Re: RFP for ...')")
    executive_summary: str = Field(
        description="1-3 paragraph executive summary of the response and value proposition"
    )
    email_body: str = Field(
        description="Full, customer-ready markdown email response with greeting and closing"
    )
    requirement_responses: List[RequirementResponseItem] = Field(
        default_factory=list, description="Per-requirement responses citing source evidence"
    )
    clarification_questions: List[ResponseClarificationItem] = Field(
        default_factory=list, description="Clarifying questions to present to client"
    )
    unsupported_items: List[str] = Field(
        default_factory=list,
        description="Requirements or questions that could not be supported by available company evidence",
    )


def build_generation_user_prompt(
    context: ProposalContext,
    requirements: List[ExtractedRequirement],
    sources: List[RetrievedSource],
) -> str:
    """Construct prompt combining proposal context, requirements, and retrieved evidence."""
    sections = [
        f"COMPANY CONTEXT: Response on behalf of company '{context.company_id}'.",
        "",
        f"CLIENT INQUIRY SUBJECT: {context.subject}",
        "",
        "CLIENT EMAIL BODY:",
        context.body.strip() if context.body else "[No body text provided]",
        "",
    ]

    # Include attachment summary if present
    if context.attachments_text:
        sections.append("INBOUND ATTACHMENTS (CLIENT REQUIREMENTS):")
        for idx, att in enumerate(context.attachments_text, 1):
            sections.append(f"--- Attachment {idx} ---")
            sections.append(att[:2000].strip())
        sections.append("")

    # Include Extracted Requirements
    sections.append("EXTRACTED CLIENT REQUIREMENTS TO ADDRESS:")
    if requirements:
        for req in requirements:
            req_id = req.requirement_id
            cat = req.category
            prio = req.priority
            exp = "Explicit" if req.explicit else "Inferred"
            txt = req.text or req.description
            sections.append(f"- [{req_id}] ({cat}, Priority: {prio}, {exp}): {txt}")
    else:
        sections.append("- General business request (no discrete requirements extracted).")
    sections.append("")

    # Include Retrieved Knowledge Evidence
    sections.append("RETRIEVED COMPANY KNOWLEDGE BASE EVIDENCE (ONLY USE THESE FACTS):")
    if sources:
        for idx, src in enumerate(sources, 1):
            sec_info = f" ({src.section})" if src.section else ""
            sections.append(f"Source [{src.source_id}] - {src.title}{sec_info}:")
            sections.append(f"\"{src.content.strip() if src.content else '[Title reference only]'}\"")
            sections.append("")
    else:
        sections.append("[NO RETRIEVED COMPANY EVIDENCE AVAILABLE - Flag all factual claims for human review.]")
        sections.append("")

    sections.append(
        "Please generate the structured response draft strictly adhering to anti-hallucination rules."
    )
    return "\n".join(sections)
